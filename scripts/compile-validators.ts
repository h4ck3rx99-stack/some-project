/**
 * Precompile Ajv validators for every vendored UCP version into standalone ES modules.
 *
 * Why: Cloudflare Workers forbid `new Function`/eval, which Ajv uses to compile schemas at
 * runtime. Ajv's "standalone" mode emits plain JS at build time instead (see docs/DECISIONS.md).
 *
 * Output: src/ucp/generated/validators-<version>.js (+ .d.ts). Run after updating schemas:
 *   npm run build:validators
 */
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { UCP_VERSIONS } from '../src/ucp/versions.ts';

const ROOT = 'schemas/ucp';
const OUT = 'src/ucp/generated';

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.json') ? [p] : [];
  });
}

/**
 * Entry points CartProbe validates. Keys become exported function names.
 * `profile` for versions without profile.json (<= 2026-04-08) uses a thin wrapper that mirrors
 * the documented profile shape: an object with a required `ucp` member validated against
 * ucp.json#/$defs/business_schema (spec overview, "Business Profile").
 */
function entries(version: string, hasProfileJson: boolean): Record<string, string> {
  const base = 'https://ucp.dev/schemas';
  return {
    profile: hasProfileJson ? `${base}/profile.json#/$defs/business_schema` : 'cartprobe:profile-wrapper',
    catalogSearchResponse: `${base}/shopping/catalog_search.json#/$defs/search_response`,
    checkout: `${base}/shopping/checkout.json`,
  };
}

for (const version of UCP_VERSIONS) {
  const dir = join(ROOT, version);
  const ajv = new Ajv2020({
    strict: false, // UCP schemas carry custom annotations (ucp_request, name, ...)
    allErrors: true,
    code: { source: true, esm: true },
  });
  addFormats(ajv);
  let hasProfileJson = false;
  for (const file of walk(dir)) {
    const schema = JSON.parse(readFileSync(file, 'utf8'));
    if (relative(dir, file) === 'profile.json') hasProfileJson = true;
    ajv.addSchema(schema);
  }
  if (!hasProfileJson) {
    ajv.addSchema({
      $id: 'cartprobe:profile-wrapper',
      type: 'object',
      required: ['ucp'],
      properties: { ucp: { $ref: 'https://ucp.dev/schemas/ucp.json#/$defs/business_schema' } },
    });
  }
  const refs = entries(version, hasProfileJson);
  // Ajv standalone emits CommonJS require() calls for runtime helpers even in ESM mode.
  // Hoist them into static imports so both wrangler (esbuild) and vitest (vite) can bundle them.
  const raw = standaloneCode(ajv, refs);
  const mods = [...new Set([...raw.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]!))];
  let code = raw;
  mods.forEach((m, i) => {
    code = code.split(`require("${m}")`).join(`__dep${i}`);
  });
  code = mods.map((m, i) => `import __dep${i} from "${m}.js";`).join('\n') + '\n' + code;
  const file = join(OUT, `validators-${version}.js`);
  writeFileSync(
    file,
    `// GENERATED by scripts/compile-validators.ts from schemas/ucp/${version}. Do not edit.\n/* eslint-disable */\n// @ts-nocheck\n${code.replace('"use strict";', '')}`,
  );
  writeFileSync(
    join(OUT, `validators-${version}.d.ts`),
    `// GENERATED. Do not edit.\nimport type { GeneratedValidator } from '../validatorTypes';\n` +
      Object.keys(refs)
        .map((k) => `export declare const ${k}: GeneratedValidator;`)
        .join('\n') +
      '\n',
  );
  console.log(`compiled ${version}: ${Object.keys(refs).join(', ')}`);
}
