/**
 * Bundle test/fixtures/** into one TS module so both Vitest (workerd) and the mock-store Worker
 * can import them without filesystem access. Output: test/fixtures/fixtures.generated.ts
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = 'test/fixtures';
function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const files = walk(ROOT)
  .filter((f) => !f.endsWith('.ts'))
  .sort();
const entries = files.map(
  (f) => `  ${JSON.stringify(relative(ROOT, f))}: ${JSON.stringify(readFileSync(f, 'utf8'))},`,
);
writeFileSync(
  join(ROOT, 'fixtures.generated.ts'),
  `// GENERATED by scripts/build-fixtures.ts. Do not edit; edit files under test/fixtures/ instead.\nexport const RAW_FIXTURES: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`bundled ${files.length} fixtures`);
