/**
 * Compile content/fix/*.md (our own trusted content) to HTML at build time so the Worker ships
 * no Markdown parser. Output: src/content/fixGuides.generated.ts
 * Also bundles test fixtures (scripts/build-fixtures.ts) so one `npm run build:content` keeps both fresh.
 */
import { marked } from 'marked';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import './build-fixtures.ts';

const DIR = 'content/fix';
const out: Record<string, { title: string; html: string; markdown: string }> = {};
for (const f of readdirSync(DIR)
  .filter((x) => x.endsWith('.md'))
  .sort()) {
  const md = readFileSync(join(DIR, f), 'utf8');
  const title = /^#\s+(.+)$/m.exec(md)?.[1]?.trim() ?? f;
  const body = md.replace(/^#\s+.+\n/, '');
  out[f.replace(/\.md$/, '')] = { title, html: marked.parse(body, { async: false }) as string, markdown: md };
}
writeFileSync(
  'src/content/fixGuides.generated.ts',
  `// GENERATED by scripts/build-content.ts from content/fix/*.md. Do not edit.\nexport const FIX_GUIDES: Record<string, { title: string; html: string; markdown: string }> = ${JSON.stringify(out, null, 1)};\n`,
);
console.log(`compiled ${Object.keys(out).length} fix guides`);
